# -*- coding: utf-8 -*-
"""Post-process compare_dataset_stems_v2 Markdown reports.

This script parses the Markdown report generated by
``scripts/compare_dataset_stems_v2.py`` and then copies or moves the matched
files into a target directory.

Supported use cases:
1. Move files that exist only in Group A.
2. Move files that exist only in Group B.
3. Move common files from Group A, Group B, or both groups.

The script reads full source paths directly from the report, so it works well
for one-to-many and many-to-many comparisons.

后处理 compare_dataset_stems_v2 Markdown 报告。

这个脚本会解析由 ``scripts/compare_dataset_stems_v2.py`` 生成的 Markdown 报告，然后将匹配的文件复制或移动到目标目录。

支持的使用场景：
1. 移动仅存在于 A 组的文件。
2. 移动仅存在于 B 组的文件。
3. 移动 A 组、B 组或两个组都有的公共文件。

脚本会直接从报告中读取完整的源路径，所以对于一对多和多对多的比较也很适用。

"""

from __future__ import annotations

import argparse
import datetime as dt
import os
import os.path as osp
import re
import shutil
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable


# ============================================
# CONFIG 区域 - 可直接修改
# ============================================

REPORT_PATH: str = r"D:\A000_report_txt\20260612_248_733.md"
TARGET_DIR: str = r"D:\A000_report_txt\248_734_json"

# 可选: only_a / only_b / common
SECTION: str = "common"

# 当 SECTION=common 时生效，可选: a / b / both
COMMON_GROUP: str = "a"

# 可选: move / copy
ACTION: str = "move"

# 默认先演练，不真正搬运
DRY_RUN: bool = False

# 目标端已存在同名文件时，是否覆盖
OVERWRITE: bool = False


SECTION_TITLE_MAP = {
    "only_a": "## Stems Only in Group A",
    "only_b": "## Stems Only in Group B",
    "common": "## Common Stems",
}

GROUP_HEADER_MAP = {
    "group_a": "## Group A Directories",
    "group_b": "## Group B Directories",
}

PATH_PATTERN = re.compile(r"`([^`]+)`")


@dataclass(frozen=True)
class FileRecord:
    """A single file extracted from the report."""

    stem: str
    section: str
    group: str
    category: str
    source_path: Path


@dataclass(frozen=True)
class ParsedReport:
    """Structured report content."""

    group_a_dirs: list[Path]
    group_b_dirs: list[Path]
    records: list[FileRecord]


def parse_args() -> argparse.Namespace:
    """Parse command-line arguments."""
    parser = argparse.ArgumentParser(
        description=(
            "Parse a compare_dataset_stems_v2 Markdown report and move/copy "
            "the matched files to a target directory."
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""Examples:

1. 使用脚本顶部配置直接运行:
   python scripts/postprocess_compare_dataset_report.py

2. 处理 Only in Group A:
   python scripts/postprocess_compare_dataset_report.py ^
       --report D:\\A000_report_txt\\20260612_0001.md ^
       --target D:\\output ^
       --section only_a ^
       --action move

3. 处理共有文件，只搬 Group B:
   python scripts/postprocess_compare_dataset_report.py ^
       --report D:\\A000_report_txt\\20260612_0001.md ^
       --target D:\\output ^
       --section common ^
       --common-group b ^
       --action copy
""",
    )
    parser.add_argument("--report", type=Path, help="Markdown report path.")
    parser.add_argument("--target", type=Path, help="Target directory path.")
    parser.add_argument(
        "--section",
        choices=("only_a", "only_b", "common"),
        help="Which report section to process.",
    )
    parser.add_argument(
        "--common-group",
        choices=("a", "b", "both"),
        help="When section=common, choose which group's files to process.",
    )
    parser.add_argument(
        "--action",
        choices=("move", "copy"),
        help="Whether to move or copy files.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Preview operations without changing files.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Overwrite destination files if they already exist.",
    )
    return parser.parse_args()


def load_settings(args: argparse.Namespace) -> dict[str, object]:
    """Merge script config and CLI args."""
    settings: dict[str, object] = {
        "report": REPORT_PATH,
        "target": TARGET_DIR,
        "section": SECTION,
        "common_group": COMMON_GROUP,
        "action": ACTION,
        "dry_run": DRY_RUN,
        "overwrite": OVERWRITE,
    }

    if args.report is not None:
        settings["report"] = str(args.report)
    if args.target is not None:
        settings["target"] = str(args.target)
    if args.section is not None:
        settings["section"] = args.section
    if args.common_group is not None:
        settings["common_group"] = args.common_group
    if args.action is not None:
        settings["action"] = args.action
    if args.dry_run:
        settings["dry_run"] = True
    if args.overwrite:
        settings["overwrite"] = True

    return settings


def normalize_section(section: str) -> str:
    """Validate and normalize section name."""
    if section not in SECTION_TITLE_MAP:
        raise ValueError(
            f"Unsupported section '{section}'. "
            "Use only_a, only_b, or common."
        )
    return section


def normalize_common_group(common_group: str) -> str:
    """Validate and normalize common group selector."""
    if common_group not in {"a", "b", "both"}:
        raise ValueError(
            f"Unsupported common_group '{common_group}'. "
            "Use a, b, or both."
        )
    return common_group


def parse_directory_block(lines: list[str], header: str) -> list[Path]:
    """Parse directory paths under a report header."""
    directories: list[Path] = []
    in_block = False

    for line in lines:
        stripped = line.strip()
        if stripped == header:
            in_block = True
            continue
        if in_block and stripped.startswith("## "):
            break
        if in_block and stripped.startswith("- "):
            paths = PATH_PATTERN.findall(stripped)
            if paths:
                directories.append(Path(paths[0]))

    return directories


def parse_report(report_path: Path) -> ParsedReport:
    """Parse the compare report into structured records."""
    text = report_path.read_text(encoding="utf-8")
    lines = text.splitlines()

    group_a_dirs = parse_directory_block(lines, GROUP_HEADER_MAP["group_a"])
    group_b_dirs = parse_directory_block(lines, GROUP_HEADER_MAP["group_b"])

    records: list[FileRecord] = []
    current_section = ""
    current_stem = ""

    for line in lines:
        stripped = line.strip()

        if stripped.startswith("## "):
            if stripped == SECTION_TITLE_MAP["only_a"]:
                current_section = "only_a"
            elif stripped == SECTION_TITLE_MAP["only_b"]:
                current_section = "only_b"
            elif stripped == SECTION_TITLE_MAP["common"]:
                current_section = "common"
            else:
                current_section = ""
            current_stem = ""
            continue

        if not current_section:
            continue

        if stripped.startswith("- `") and stripped.endswith("`"):
            matches = PATH_PATTERN.findall(stripped)
            current_stem = matches[0] if matches else ""
            continue

        if not current_stem or not stripped.startswith("- "):
            continue

        records.extend(
            parse_record_line(
                stripped=stripped,
                current_section=current_section,
                current_stem=current_stem,
            )
        )

    return ParsedReport(
        group_a_dirs=group_a_dirs,
        group_b_dirs=group_b_dirs,
        records=records,
    )


def parse_record_line(
    stripped: str,
    current_section: str,
    current_stem: str,
) -> list[FileRecord]:
    """Parse a detail line into one or more file records."""
    if current_section == "common":
        return parse_common_record_line(stripped, current_stem)
    return parse_single_group_record_line(stripped, current_section, current_stem)


def parse_single_group_record_line(
    stripped: str,
    current_section: str,
    current_stem: str,
) -> list[FileRecord]:
    """Parse an Only-A or Only-B detail line."""
    prefix, _, _ = stripped.partition(":")
    category = prefix.replace("- ", "").strip().lower()
    paths = [Path(path) for path in PATH_PATTERN.findall(stripped)]
    if not paths:
        return []

    group = "a" if current_section == "only_a" else "b"
    return [
        FileRecord(
            stem=current_stem,
            section=current_section,
            group=group,
            category=category,
            source_path=path,
        )
        for path in paths
    ]


def parse_common_record_line(
    stripped: str,
    current_stem: str,
) -> list[FileRecord]:
    """Parse a Common Stems detail line."""
    prefix, _, _ = stripped.partition(":")
    prefix_text = prefix.replace("- ", "").strip().lower()
    paths = [Path(path) for path in PATH_PATTERN.findall(stripped)]
    if not paths:
        return []

    if prefix_text.startswith("group a "):
        group = "a"
        category = prefix_text.replace("group a ", "", 1)
    elif prefix_text.startswith("group b "):
        group = "b"
        category = prefix_text.replace("group b ", "", 1)
    else:
        return []

    return [
        FileRecord(
            stem=current_stem,
            section="common",
            group=group,
            category=category,
            source_path=path,
        )
        for path in paths
    ]


def select_records(
    parsed_report: ParsedReport,
    section: str,
    common_group: str,
) -> list[FileRecord]:
    """Filter parsed records according to the requested mode."""
    selected: list[FileRecord] = []
    seen_paths: set[Path] = set()

    for record in parsed_report.records:
        if record.section != section:
            continue
        if section == "common":
            if common_group == "a" and record.group != "a":
                continue
            if common_group == "b" and record.group != "b":
                continue
        if record.source_path in seen_paths:
            continue
        seen_paths.add(record.source_path)
        selected.append(record)

    return selected


def safe_slug(text: str) -> str:
    """Convert a path-like string into a filesystem-safe folder name."""
    cleaned = re.sub(r"[<>:\"/\\\\|?*]+", "_", text.strip())
    cleaned = cleaned.strip(" ._")
    return cleaned or "unknown_root"


def build_root_mappings(parsed_report: ParsedReport) -> dict[str, list[tuple[Path, str]]]:
    """Build source-root mappings for Group A and Group B."""
    mappings: dict[str, list[tuple[Path, str]]] = {"a": [], "b": []}

    for index, root in enumerate(parsed_report.group_a_dirs, start=1):
        label = f"group_a_{index:02d}_{safe_slug(root.name or str(root))}"
        mappings["a"].append((root, label))

    for index, root in enumerate(parsed_report.group_b_dirs, start=1):
        label = f"group_b_{index:02d}_{safe_slug(root.name or str(root))}"
        mappings["b"].append((root, label))

    return mappings


def find_matching_root(
    source_path: Path,
    root_mappings: list[tuple[Path, str]],
) -> tuple[Path | None, str]:
    """Find the longest source root that contains the given file path."""
    best_root: Path | None = None
    best_label = "unmatched"
    best_length = -1

    source_parts = source_path.parts
    for root, label in root_mappings:
        root_parts = root.parts
        if len(root_parts) > len(source_parts):
            continue
        if source_parts[: len(root_parts)] == root_parts and len(root_parts) > best_length:
            best_root = root
            best_label = label
            best_length = len(root_parts)

    return best_root, best_label


def build_destination_path(
    record: FileRecord,
    target_dir: Path,
    root_lookup: dict[str, list[tuple[Path, str]]],
) -> Path:
    """Build a stable destination path for a record."""
    matched_root, root_label = find_matching_root(
        record.source_path,
        root_lookup.get(record.group, []),
    )

    if matched_root is not None:
        relative_path = record.source_path.relative_to(matched_root)
        return target_dir / root_label / relative_path

    return target_dir / f"group_{record.group}_unmatched" / record.source_path.name


def ensure_destination_parent(path: Path, dry_run: bool) -> None:
    """Create parent directory when needed."""
    if dry_run:
        return
    path.parent.mkdir(parents=True, exist_ok=True)


def transfer_file(
    source_path: Path,
    destination_path: Path,
    action: str,
    overwrite: bool,
    dry_run: bool,
) -> tuple[str, str]:
    """Execute a single copy or move operation."""
    if not source_path.exists():
        return "not_found", f"Source not found: {source_path}"

    if destination_path.exists():
        if not overwrite:
            return "skipped_exists", f"Destination exists: {destination_path}"
        if not dry_run and destination_path.is_file():
            destination_path.unlink()

    if dry_run:
        return "dry_run", f"{action.upper()} {source_path} -> {destination_path}"

    ensure_destination_parent(destination_path, dry_run=False)

    if action == "copy":
        shutil.copy2(source_path, destination_path)
    else:
        shutil.move(str(source_path), str(destination_path))

    return "success", f"{action.upper()} {source_path} -> {destination_path}"


def format_summary_counter(results: list[tuple[str, str]]) -> dict[str, int]:
    """Count result statuses."""
    summary = {
        "success": 0,
        "dry_run": 0,
        "not_found": 0,
        "skipped_exists": 0,
        "failed": 0,
    }
    for status, _ in results:
        summary[status] = summary.get(status, 0) + 1
    return summary


def write_log(
    log_dir: Path,
    report_path: Path,
    target_dir: Path,
    section: str,
    common_group: str,
    action: str,
    dry_run: bool,
    overwrite: bool,
    records: Iterable[FileRecord],
    results: list[tuple[str, str]],
) -> Path:
    """Write an execution log file."""
    log_dir.mkdir(parents=True, exist_ok=True)
    timestamp = dt.datetime.now().strftime("%Y%m%d_%H%M%S")
    log_path = log_dir / f"postprocess_log_{timestamp}.txt"
    summary = format_summary_counter(results)

    with open(log_path, "w", encoding="utf-8") as handle:
        handle.write("=" * 70 + "\n")
        handle.write("compare_dataset_stems_v2 后处理日志\n")
        handle.write("=" * 70 + "\n")
        handle.write(
            f"执行时间: {dt.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n"
        )
        handle.write(f"报告路径: {report_path}\n")
        handle.write(f"目标目录: {target_dir}\n")
        handle.write(f"处理分区: {section}\n")
        handle.write(f"共有分组: {common_group}\n")
        handle.write(f"执行动作: {action}\n")
        handle.write(f"演练模式: {dry_run}\n")
        handle.write(f"允许覆盖: {overwrite}\n")
        handle.write(f"匹配文件数: {sum(1 for _ in records)}\n")
        handle.write("=" * 70 + "\n\n")

        handle.write("结果汇总\n")
        handle.write("-" * 40 + "\n")
        handle.write(f"成功执行: {summary.get('success', 0)}\n")
        handle.write(f"演练预览: {summary.get('dry_run', 0)}\n")
        handle.write(f"源文件缺失: {summary.get('not_found', 0)}\n")
        handle.write(f"目标已存在: {summary.get('skipped_exists', 0)}\n")
        handle.write(f"执行失败: {summary.get('failed', 0)}\n\n")

        handle.write("详细结果\n")
        handle.write("-" * 40 + "\n")
        for status, message in results:
            handle.write(f"[{status}] {message}\n")

    return log_path


def main() -> None:
    """Run the report post-processing workflow."""
    args = parse_args()
    settings = load_settings(args)

    report_path = Path(str(settings["report"]))
    target_dir = Path(str(settings["target"]))
    section = normalize_section(str(settings["section"]))
    common_group = normalize_common_group(str(settings["common_group"]))
    action = str(settings["action"])
    dry_run = bool(settings["dry_run"])
    overwrite = bool(settings["overwrite"])

    if not report_path.exists():
        print(f"Error: Report not found: {report_path}", file=sys.stderr)
        sys.exit(1)

    if action not in {"move", "copy"}:
        print(f"Error: Unsupported action: {action}", file=sys.stderr)
        sys.exit(1)

    parsed_report = parse_report(report_path)
    selected_records = select_records(parsed_report, section, common_group)
    root_lookup = build_root_mappings(parsed_report)

    print(f"[INFO] Report: {report_path}")
    print(f"[INFO] Target: {target_dir}")
    print(f"[INFO] Section: {section}")
    print(f"[INFO] Common group: {common_group}")
    print(f"[INFO] Action: {action}")
    print(f"[INFO] Dry run: {dry_run}")
    print(f"[INFO] Overwrite: {overwrite}")
    print(f"[INFO] Matched files: {len(selected_records)}")

    results: list[tuple[str, str]] = []
    for record in selected_records:
        destination_path = build_destination_path(
            record=record,
            target_dir=target_dir,
            root_lookup=root_lookup,
        )
        try:
            ensure_destination_parent(destination_path, dry_run=dry_run)
            result = transfer_file(
                source_path=record.source_path,
                destination_path=destination_path,
                action=action,
                overwrite=overwrite,
                dry_run=dry_run,
            )
        except Exception as exc:  # noqa: BLE001
            result = (
                "failed",
                f"{action.upper()} {record.source_path} -> "
                f"{destination_path} failed: {exc}",
            )
        results.append(result)

    log_path = write_log(
        log_dir=target_dir,
        report_path=report_path,
        target_dir=target_dir,
        section=section,
        common_group=common_group,
        action=action,
        dry_run=dry_run,
        overwrite=overwrite,
        records=selected_records,
        results=results,
    )

    summary = format_summary_counter(results)
    print("")
    print("=" * 60)
    print("后处理完成")
    print("=" * 60)
    print(f"匹配文件:   {len(selected_records)}")
    print(f"成功执行:   {summary.get('success', 0)}")
    print(f"演练预览:   {summary.get('dry_run', 0)}")
    print(f"源文件缺失: {summary.get('not_found', 0)}")
    print(f"目标已存在: {summary.get('skipped_exists', 0)}")
    print(f"执行失败:   {summary.get('failed', 0)}")
    print(f"日志文件:   {log_path}")
    print("=" * 60)


if __name__ == "__main__":
    main()


